    #[test]
    fn import_reads_packets_and_granules() {
        let setup = setup_headers().get(118_203_318).unwrap().to_vec();
        let id = build_id_header(2, 48_000);
        let comment = build_comment_header("test");
        let a = [0x11u8; 10];
        let b = [0x22u8; 20];
        let c = [0x33u8; 30];

        let mut mux = OggMuxer::new(7);
        assert!(mux.write_page(&[&id], 0, true, false));
        assert!(mux.write_page(&[&comment, &setup], 0, false, false));
        assert!(mux.write_page(&[&a], 100, false, false));
        assert!(mux.write_page(&[&b, &c], 300, false, true));
        let ogg = mux.finish();

        let import = import_ogg(&ogg).expect("import");
        assert_eq!(import.channels, 2);
        assert_eq!(import.sample_rate, 48_000);
        assert_eq!(import.setup_crc32, 118_203_318);
        assert_eq!(import.audio_packets, vec![a.to_vec(), b.to_vec(), c.to_vec()]);
        assert_eq!(import.granules, vec![100, 300, 300]);
        assert_eq!(import.num_frames(), 300);

        // Seek table: one (offset, granule) entry per audio packet.
        let data = import.vorbis_data();
        assert_eq!(&data[0..4], &118_203_318u32.to_le_bytes());
        let entry = |at: usize| {
            (
                u32::from_le_bytes(data[at..at + 4].try_into().unwrap()),
                u32::from_le_bytes(data[at + 4..at + 8].try_into().unwrap()),
            )
        };
        assert_eq!(entry(4), (0, 100));
        assert_eq!(entry(12), (12, 300)); // 2 + 10
        assert_eq!(entry(20), (34, 300)); // 12 + 2 + 20
        assert_eq!(data.len(), 28);

        // Framing: u16 size then `size` payload bytes (no flags byte), then a
        // zero-length terminator.
        let bytes = import.sample_data().unwrap();
        assert_eq!(u16::from_le_bytes([bytes[0], bytes[1]]), 10);
        assert_eq!(bytes[2], 0x11); // first payload byte
        assert_eq!(bytes.len(), 2 + 10 + 2 + 20 + 2 + 30 + 2);
        assert_eq!(&bytes[bytes.len() - 2..], &[0, 0]);
    }

    #[test]
    fn sample_data_uses_raw_fmod_framing() {
        // FMOD stores `u16 length` + exactly `length` raw Vorbis bytes per
        // packet, with no flags byte (verified against a real FMOD bank and the
        // reference decoder). Lock the exact bytes so this cannot regress.
        let import = VorbisImport {
            channels: 1,
            sample_rate: 44_100,
            setup_crc32: 118_203_318,
            audio_packets: vec![vec![0xAA, 0xBB], vec![0xCC]],
            granules: vec![1_000, 2_000],
        };
        let data = import.sample_data().unwrap();
        assert_eq!(
            data,
            vec![0x02, 0x00, 0xAA, 0xBB, 0x01, 0x00, 0xCC, 0x00, 0x00]
        );

        // Each seek offset points at a packet's `u16` length prefix.
        let chunk = import.vorbis_data();
        let entry = |at: usize| {
            (
                u32::from_le_bytes(chunk[at..at + 4].try_into().unwrap()),
                u32::from_le_bytes(chunk[at + 4..at + 8].try_into().unwrap()),
            )
        };
        assert_eq!(entry(4), (0, 1_000));
        assert_eq!(entry(12), (4, 2_000)); // 2 + 2
    }

    #[test]
    fn import_round_trips_through_a_bank() {
        let bank = synthetic_vorbis_bank();
        let ogg = build_ogg(&bank, 0).unwrap();

        let rebuilt = import_ogg_to_bank(&ogg, "music").expect("import to bank");
        let parsed = crate::fsb::Fsb5::parse(&rebuilt).expect("reparse");

        assert_eq!(parsed.format, SoundFormat::Vorbis);
        assert_eq!(parsed.samples[0].name, "music");
        let vorbis = parsed.samples[0].vorbis_data().expect("VORBISDATA");
        assert_eq!(vorbis.setup_crc32, 118_203_318);

        let packets: Vec<Vec<u8>> = parsed
            .vorbis_packets(0)
            .unwrap()
            .map(|packet| packet.data.to_vec())
            .collect();
        assert_eq!(packets, vec![vec![0xAA, 0xBB], vec![0xCC]]);
    }

